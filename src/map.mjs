export function invert(m){ const r={}; for (const k of Object.keys(m)) { if (m[k]!==k && !(m[k] in r)) r[m[k]]=k; } return r; }
export function convert(text, m){
  const toFa = m, toEn = invert(m);
  let fa=0, en=0;
  for (const ch of text){ if (/[\u0600-\u06FF\uFB50-\uFEFF\u200C\u00AB\u00BB\u00D7]/.test(ch)) fa++; else if (/[A-Za-z]/.test(ch)) en++; }
  const table = fa > en ? toEn : toFa;
  let out=''; for (const ch of text) out += (ch in table) ? table[ch] : ch; return out;
}
